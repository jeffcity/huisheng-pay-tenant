const assert = require('node:assert/strict');
const puppeteer = require('puppeteer-core');

(async () => {
  const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--no-sandbox', '--allow-file-access-from-files'] });
  try {
    const page = await browser.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.setViewport({ width: 1124, height: 968 });
    await page.goto(`file://${process.argv[2]}#merchantList`);
    await page.waitForSelector('iframe');
    const frame = await (await page.$('iframe')).contentFrame();
    await frame.waitForSelector('[data-detail="MCH-1188"]');
    assert.equal(await frame.$('#businessView'), null);
    assert.equal(await frame.$$eval('#merchantRows tr', rows => rows.length), 5);
    await frame.type('#keyword', '东盛');
    assert.equal(await frame.$$eval('#merchantRows tr', rows => rows.length), 1);
    await frame.$eval('#keyword', el => { el.value = ''; el.dispatchEvent(new Event('input', { bubbles: true })); });
    assert.equal(await frame.$$eval('#merchantRows tr', rows => rows.length), 5);
    await frame.click('[data-detail="MCH-1188"]');
    await frame.click('[data-tab="跑量统计"]');
    assert.equal(await frame.$eval('[data-tab="跑量统计"]', el => el.getAttribute('aria-selected')), 'true');
    await frame.click('[data-tab="接入信息"]');
    const values = () => frame.$$eval('[data-whitelist-entry]', els => els.map(el => el.value));
    const set = (selector, value) => frame.$eval(selector, (el, value) => { el.value = value; el.dispatchEvent(new Event('input', { bubbles: true })); }, value);
    const save = () => frame.click('[data-access-save]');
    const error = () => frame.$eval('#modalError', el => el.textContent);
    assert.deepEqual(await values(), ['45.61.20.41']);
    assert.equal(await frame.$eval('[data-access-save]', el => el.textContent.trim()), '保存');
    await frame.click('#addAccessWhitelist');
    await frame.click('#addAccessWhitelist');
    assert.equal((await values()).length, 3);
    await set('#accessWhitelist-1', '999.1.1.1');
    await save();
    assert.match(await error(), /有效/);
    await set('#accessWhitelist-1', '45.61.20.41');
    await save();
    assert.match(await error(), /重复/);
    await set('#accessWhitelist-1', '8.8.8.8');
    await set('#accessWhitelist-2', '1.1.1.0/24');
    await save();
    assert.match(await error(), /2FA/);
    await set('#access2fa-shared', '123456');
    await save();
    assert.match(await frame.$eval('#modal', el => el.textContent), /8\.8\.8\.8, 1\.1\.1\.0\/24/);
    await frame.click('#accessChangeConfirm');
    await frame.waitForSelector('#backToAccess');
    await frame.click('#backToAccess');
    assert.deepEqual(await values(), ['45.61.20.41', '8.8.8.8', '1.1.1.0/24']);
    await frame.click('[aria-label="删除白名单 IP 2"]');
    assert.deepEqual(await values(), ['45.61.20.41', '1.1.1.0/24']);
    await set('#access2fa-shared', '123456');
    await save();
    await frame.click('#accessChangeConfirm');
    await frame.waitForSelector('#backToAccess');
    await frame.click('#backToAccess');
    assert.deepEqual(await values(), ['45.61.20.41', '1.1.1.0/24']);
    for (const width of [1124, 768, 375]) {
      await page.setViewport({ width, height: 968 });
      assert.equal(await frame.$eval('#accessWhitelistList', el => el.scrollWidth <= el.clientWidth), true, `white list overflow at ${width}`);
    }
    await frame.click('[aria-label="删除白名单 IP 2"]');
    await frame.click('[aria-label="删除白名单 IP 1"]');
    assert.deepEqual(await values(), ['']);
    assert.equal(await frame.$eval('#accessWhitelist-0', el => el === document.activeElement), true);
    await page.setViewport({ width: 1124, height: 968 });
    await frame.click('#modalClose');
    await frame.click('[data-wallet-detail="MCH-1188"]');
    const balances = () => frame.$$eval('#modal .mini-table tbody tr', rows => rows.slice(0, 3).map(row => [...row.cells].slice(1, 5).map(cell => cell.textContent.trim())));
    const original = await balances();
    const openAdjust = wallet => frame.click(`[data-wallet-adjust="MCH-1188"][data-adjust-wallet="${wallet}"]`);
    await openAdjust('提款钱包');
    await frame.click('#walletAdjustSubmit');
    assert.match(await error(), /有效金额/);
    await set('#walletAdjustAmount', '0');
    await frame.click('#walletAdjustSubmit');
    assert.match(await error(), /有效金额/);
    await set('#walletAdjustAmount', '0.001');
    await frame.click('#walletAdjustSubmit');
    assert.match(await error(), /有效金额/);
    await set('#walletAdjustAmount', '1.25');
    await frame.click('#walletAdjustSubmit');
    assert.match(await error(), /原因/);
    await set('#walletAdjustReason', '测试调整依据');
    await frame.click('#walletAdjustSubmit');
    assert.match(await error(), /2FA/);
    await frame.select('#walletAdjustDirection', 'subtract');
    await set('#walletAdjustAmount', '814020.01');
    await frame.click('#walletAdjustSubmit');
    assert.match(await error(), /不能超过可用余额/);
    await set('#walletAdjustAmount', '1.25');
    await set('#walletAdjust2fa', '123456');
    await frame.click('#walletAdjustSubmit');
    assert.match(await frame.$eval('#walletAdjustmentPreview', el => el.textContent), /814,018.75/);
    await frame.click('#walletAdjustBack');
    assert.equal(await frame.$eval('#walletAdjustAmount', el => el.disabled), false);
    await frame.click('#walletAdjustCancel');
    assert.deepEqual(await balances(), original, 'cancel must not mutate balances');
    const toCents = value => Math.round(Number(value.replaceAll(',', '')) * 100);
    for (const [index, wallet] of ['提款钱包', '代收钱包', '代付钱包'].entries()) {
      for (const direction of ['add', 'subtract']) {
        const before = await balances();
        await openAdjust(wallet);
        await frame.select('#walletAdjustDirection', direction);
        await set('#walletAdjustAmount', '1.25');
        await set('#walletAdjustReason', '<b>余额调整回归</b>');
        await set('#walletAdjust2fa', '123456');
        await frame.click('#walletAdjustSubmit');
        // Repeated confirmation must not apply the same adjustment twice.
        await frame.$eval('#walletAdjustSubmit', el => { el.click(); el.click(); });
        await frame.waitForSelector('[data-wallet-adjust]');
        const after = await balances();
        const delta = direction === 'add' ? 125 : -125;
        assert.equal(toCents(after[index][1]), toCents(before[index][1]) + delta);
        assert.equal(after[index][2], before[index][2], 'frozen balance unchanged');
        assert.equal(toCents(after[index][3]), toCents(before[index][3]) + delta);
        before.forEach((row, other) => { if (other !== index) assert.deepEqual(after[other], row); });
      }
    }
    assert.deepEqual(await balances(), original);
    assert.equal(await frame.$$eval('#modal .mini-table', tables => tables[1].querySelectorAll('tbody tr').length), 6);
    assert.equal(await frame.$$eval('#modal .mini-table tbody b', els => els.length), 0, 'reason rendered as text');
    await frame.click('#modalClose');
    await frame.click('[data-detail="MCH-1188"]');
    await frame.click('[data-tab="操作日志"]');
    assert.equal(await frame.$$eval('#modal tbody tr', rows => rows.filter(row => row.textContent.includes('商户钱包资金调整')).length), 6);
    await frame.click('[data-tab="钱包账户"]');
    await openAdjust('代收钱包');
    await frame.click('#walletAdjustCancel');
    assert.equal(await frame.$eval('[data-tab="钱包账户"]', el => el.getAttribute('aria-selected')), 'true');
    assert.equal(await frame.$$eval('[data-funding-history-merchant]', els => els.length), 0);
    // Both business panels use the same adjustment flow and canonical wallet amounts.
    for (const [tabName, wallet, direction, delta] of [['代收配置', '代收钱包', 'add', 1000], ['代付配置', '代付钱包', 'subtract', -1000]]) {
      await frame.click(`[data-tab="${tabName}"]`);
      assert.equal(await frame.$$eval('[data-funding-history-merchant]', els => els.length), 0);
      const walletValues = () => frame.$eval('[data-wallet-adjust]', button => [...button.closest('tr').cells].slice(1, 4).map(cell => cell.textContent.trim()));
      const before = await walletValues();
      await openAdjust(wallet);
      assert.match(await frame.$eval('#modal .modal-head', el => el.textContent), new RegExp(wallet));
      await frame.select('#walletAdjustDirection', direction);
      await set('#walletAdjustAmount', '10');
      await set('#walletAdjustReason', '业务页钱包调整');
      await set('#walletAdjust2fa', '123456');
      await frame.click('#walletAdjustSubmit');
      await frame.click('#walletAdjustSubmit');
      assert.equal(await frame.$eval(`[data-tab="${tabName}"]`, el => el.getAttribute('aria-selected')), 'true');
      const after = await walletValues();
      assert.equal(toCents(after[0]), toCents(before[0]) + delta);
      assert.equal(after[1], before[1]);
      assert.equal(toCents(after[2]), toCents(before[2]) + delta);
      await frame.click('[data-tab="钱包账户"]');
      const shared = (await balances()).find(row => row[0] === wallet);
      assert.deepEqual(shared.slice(1), after);
    }
    // Callback configuration is scoped to each business, not the incoming API whitelist.
    await frame.click('[data-tab="代收配置"]');
    assert.equal(await frame.$eval('#merchantCollectCallbackIp', el => el.value), '45.61.20.41');
    for (const invalid of ['999.1.1.1', '10.0.0.1', '8.8.8.0/24', ',,']) {
      await set('#merchantCollectCallbackIp', invalid);
      await frame.click('[data-business-config-save="collect"]');
      assert.match(await error(), /有效的公网/);
    }
    await set('#merchantCollectCallbackIp', '8.8.4.4, 8.8.4.4');
    await frame.click('[data-business-config-save="collect"]');
    assert.match(await error(), /不能重复/);
    const collectIp = '8.8.4.4, 2001:4860:4860::8844';
    await set('#merchantCollectCallbackIp', collectIp.replace(', ', '\n'));
    await frame.click('[data-business-config-save="collect"]');
    assert.match(await error(), /变更原因/);
    await set('#merchantCollectReason', '配置商户代收回调');
    await frame.click('[data-business-config-save="collect"]');
    await frame.waitForFunction(() => document.querySelector('#merchantCollectCallbackIp')?.value === '8.8.4.4, 2001:4860:4860::8844' && document.querySelector('#merchantCollectReason')?.value === '');
    await frame.click('[data-tab="代付配置"]');
    assert.equal(await frame.$eval('#merchantPayoutCallbackIp', el => el.value), '');
    await frame.click('[data-business-config-save="payout"]');
    assert.match(await error(), /没有变化/);
    await set('#merchantPayoutCallbackIp', '9.9.9.9');
    await set('#merchantPayoutReason', '配置商户代付回调');
    await frame.click('[data-business-config-save="payout"]');
    await frame.waitForFunction(() => document.querySelector('#merchantPayoutReason')?.value === '' && !document.querySelector('[data-business-config-save="payout"]')?.disabled);
    await frame.click('[data-tab="接入信息"]');
    assert.deepEqual(await values(), ['45.61.20.41', '1.1.1.0/24']);
    await set('#accessWhitelist-0', '1.0.0.1');
    await set('#access2fa-shared', '123456');
    await save();
    await frame.click('#accessChangeConfirm');
    await frame.waitForSelector('#backToAccess');
    await frame.click('#backToAccess');
    await frame.click('[data-tab="代收配置"]');
    assert.equal(await frame.$eval('#merchantCollectCallbackIp', el => el.value), collectIp);
    await frame.click('[data-tab="代付配置"]');
    assert.equal(await frame.$eval('#merchantPayoutCallbackIp', el => el.value), '9.9.9.9');
    await set('#merchantPayoutCallbackIp', '');
    await set('#merchantPayoutReason', '清除回调配置');
    await frame.click('[data-business-config-save="payout"]');
    await frame.waitForFunction(() => document.querySelector('#merchantPayoutReason')?.value === '' && !document.querySelector('[data-business-config-save="payout"]')?.disabled);
    await frame.click('[data-tab="代收配置"]');
    await frame.click('[data-tab="代付配置"]');
    assert.equal(await frame.$eval('#merchantPayoutCallbackIp', el => el.value), '');
    await frame.click('[data-tab="操作日志"]');
    assert.match(await frame.$eval('#modal', el => el.textContent), /回调 IP 未配置 → 9\.9\.9\.9/);
    await frame.click('#modalClose');
    await frame.click('[data-detail="MCH-2031"]');
    await frame.click('[data-tab="代收配置"]');
    assert.equal(await frame.$eval('#merchantCollectCallbackIp', el => el.value), '103.88.21.14, 103.88.21.15');
    for (const width of [1124, 768, 375]) {
      await page.setViewport({ width, height: 968 });
      assert.equal(await frame.$eval('#merchantCollectCallbackIp', el => el.getBoundingClientRect().width <= el.parentElement.clientWidth), true);
    }
    assert.deepEqual(errors, []);
    console.log('MERCHANT_ACCESS_PASS 文案、页签、多 IP 新增/删除/保存回显、格式/重复/2FA 校验、窄屏布局');
    console.log('MERCHANT_ADJUSTMENT_PASS 三钱包增减、精度/余额/原因/2FA 校验、二次确认/取消/重复提交、冻结金额不变、流水/审计、两处入口');
    console.log('MERCHANT_CONFIG_PASS 申请记录入口移除、代收/代付资金调整和余额同步、独立回调 IP 校验/保存/清空/日志/白名单隔离/商户隔离');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
